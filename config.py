# -*- coding: utf-8 -*-
"""
config.py —— 全部可调参数集中在这个文件里。

使用说明：
  1. 改完参数后直接运行  python main.py  即可，无需改其他文件。
  2. 每个 [节] 的标题行都写了"改这里"，说明这一节控制什么。
  3. 单位约定：长度一律 nm（纳米），角度一律 rad（弧度）。
"""

# ============================================================
# [1] 演示选择 ———— 改这里：DEMO_NAME 切换示例图形
# ============================================================
# 可选值:
#   'elbow_array'    肘形阵列：周期排列的 L 折线（周期 + 角点）★默认
#   'dense_lines'    密集线条阵列（周期环境，看边缘位移修正）
#   'line_end_array' 线端阵列（周期线条中间线的线端回缩修正）
#   'contact_array'  接触孔阵列（二维周期，每孔 4 个角）
#   'l_shape'        L 形图形（单图形，看角落 serif 修正）
#   't_shape'        T 形图形（凸角 + 凹角混合）
#   'line_end_gap'   线端间隙（看线端回缩修正）
#   'isolated_line'  孤立线条（与密集线条对比邻近效应）
#   'custom'         读取自定义版图文件
DEMO_NAME = "elbow_array"

# DEMO_NAME='custom' 时读取的文件：0/1 文本矩阵（空格/逗号分隔）或灰度 PNG
CUSTOM_MASK_FILE = "input_mask.txt"

# ============================================================
# [2] 仿真网格 ———— 改这里：网格分辨率
# ============================================================
GRID_N = 384            # 网格边长（像素数）；仿真视场 = GRID_N × PIXEL_SIZE_NM
PIXEL_SIZE_NM = 2.0     # 像素尺寸 (nm)，默认视场 384×2 = 768 nm
                        # （200nm 特征需要更大视场；改小到 256 可加快但视场仅 512nm）

# ============================================================
# [3] 光刻参数 ———— 改这里：光学系统
# ============================================================
WAVELENGTH_NM = 193.0   # 曝光波长 λ (nm)，ArF 浸没式光刻典型值
NA = 1.35               # 投影物镜数值孔径 NA = n·sinθ
ILLUM_TYPE = "annular"  # 照明方式: 'annular' 环形 / 'circle' 传统圆形（σ_in=0）
SIGMA_IN = 0.6          # 环形照明内相干因子 σ_in（光源内半径 / (NA/λ)）
SIGMA_OUT = 0.9         # 环形照明外相干因子 σ_out
DEFOCUS_NM = 0.0        # 离焦量 (nm)，0 = 无离焦（理想焦面）
RESIST_THRESHOLD = 0.3  # 光刻胶固定阈值模型：归一化强度 < 阈值 处形成图形
RESIST_BLUR_SIGMA_NM = 0.0  # 胶内扩散高斯模糊 σ (nm)，0 = 关闭

# 版图边界条件 ———— 改这里
#   'periodic' 周期边界（默认）：视场就是版图的一个周期，相邻周期无缝拼接。
#      FFT 循环卷积天然实现；跨视场边界的图形会自动环绕到对面。
#      这是掩模版图（reticle field）的标准假设——版图本身就是周期排布的。
#   'isolated' 孤立边界：掩模零填充到 2N 后计算（线性卷积，无环绕），
#      适合单个孤立图形，但 FFT 时间约 4 倍。
BOUNDARY_MODE = "periodic"

# ============================================================
# [4] 光源采样 ———— 改这里：精度/速度权衡（计算量 ∝ 点数×环数）
# ============================================================
# Hopkins 模型用"光源点采样法"(Abbe)数值求解：
# 把光源分成 N_SOURCE_RINGS 个同心环、每环 N_SOURCE_PTS 个点，
# 每个点算一次 FFT 传播，最后按权重求和。点数越多越准、越慢。
N_SOURCE_PTS = 24       # 每环方位角采样点数（取偶数，保证 ±f_s 严格成对）
N_SOURCE_RINGS = 6      # 径向环数（σ_in → σ_out 均分）

# ============================================================
# [5] OPC 迭代 ———— 改这里：收敛行为
# ============================================================
MAX_ITER = 60           # 最大迭代次数
EPE_TOL_NM = 2.0        # RMS EPE 收敛容差 (nm)；不宜小于像素尺寸
ETA_EDGE = 0.5          # 边缘反馈增益 η：Δ = −η·EPE
DAMPING = 0.85          # 一阶惯性阻尼系数（0~1，越大越稳、收敛越慢）。
                        # 0.85 = 高质量档（约 30~40 轮收敛，角点残差 ~4nm）；
                        # 0.6  = 快速档（约 10 轮，但角点残差 ~11nm）
MAX_EDGE_STEP_NM = 3.0  # 单次迭代边缘位移限幅 (nm)
MIN_EDGE_SEGMENT_NM = 8.0   # 边缘分段最短长度 (nm)
MAX_EDGE_SEGMENT_NM = 16.0  # 边缘分段最长长度 (nm)，超过则拆分
CORNER_EXCLUSION_NM = 8.0   # EPE 采样点距段端点/角点的避让距离 (nm)
EPE_SEARCH_NM = 60.0        # EPE 沿法线搜索半径 (nm)。角落印刷轮廓圆化约
                            # 30~45nm，搜索半径太小会找不到阈值交点、EPE 封顶，
                            # 角点反馈失去真实测量值（封顶值+切口偏移还随 serif
                            # 增长而"变差"，形成把 serif 推向极限的假反馈）
SERIF_INIT_NM = 4.0     # 角落切口（serif 种子）初始边长 s₀ (nm)
SERIF_MAX_NM = 30.0     # 切口边长上限 (nm)，超出拒收
MAX_BIAS_NM = 25.0      # 边缘累计偏置上限 (nm)：|边当前位置 − 目标位置| 不超过该值。
                        # 相当于真实 OPC 的掩模规则约束——角落区域受成像
                        # 分辨率极限制约，印刷轮廓跟不上掩模偏置，不设上限
                        # 掩模会无益地持续外扩。0 = 不限制。
ANNEAL = False          # True = 开启增益退火 η=η₀/(1+iter/10)，迭代后期更稳

# ============================================================
# [6] 像素辅助操作 ———— 改这里：清理与设计规则
# ============================================================
CLEANUP_ISLANDS = True  # 去除孤立小岛（光栅化残留的小碎块）
MIN_ISLAND_PX = 3       # 面积 ≤ 该值的连通域视为小岛（像素数）
CLEANUP_HOLES = True    # 填补小空洞
MIN_HOLE_PX = 3         # 面积 ≤ 该值的空洞视为小洞（像素数）
CLEANUP_OPEN = False    # 开运算去单像素凸起（会削掉小 serif，默认关）
ENFORCE_DR = False      # True = 违反设计规则时撤销本次移动（默认仅报告）
MIN_WIDTH_NM = 20.0     # 设计规则：最小线宽 (nm)
MIN_SPACE_NM = 20.0     # 设计规则：最小间距 (nm)

# ============================================================
# [7] 输出 ———— 改这里：文件输出
# ============================================================
OUT_DIR = "output"      # 输出目录（相对项目根目录）
SAVE_FRAMES = True      # 每次迭代保存一帧总览图 iter_%03d.png
SAVE_GIF = False        # 迭代动画（需要 imageio，环境里已装）

# ============================================================
# [8] 示例图形几何参数（每个示例一组，单位 nm）
# ============================================================
# 默认取 200nm 线宽级（k1≈1.4）：邻近效应弱、修正形态干净，
# 以周期图案为主（密集线条/线端阵列/接触孔），孤立图形留作对比。
# 注意：孤立图形线宽不宜小于 ~55nm（193nm/1.35、阈值0.3 时
# 孤立 45nm 线处于印刷极限：中心光强 ≈0.26~0.30，勉强/不能印刷）。
# 总跨度不要超过视场 768nm。
# 肘形阵列：条数、线宽、臂长、周期（中心距）。
# 约束1：臂长要明显大于线宽，否则 L 形退化成"带缺口的方块"；
# 约束2：间距 = 周期 − 臂长 需 ≥100nm（过小会印粘连）；
# 约束3：跨度 = 周期×(n-1) + 臂长 ≤ 视场 768nm
ELBOW_N, ELBOW_W, ELBOW_ARM, ELBOW_PITCH = 2, 200.0, 300.0, 420.0
# 密集线条：条数、线宽、周期（pitch = 线宽 + 间距）
LINES_N, LINES_W, LINES_PITCH = 3, 200.0, 280.0
# 线端阵列：条数、线宽、周期、中间线半长（中间线线端回缩）
LEA_N, LEA_W, LEA_PITCH, LEA_MID_HALF = 3, 200.0, 280.0, 150.0
